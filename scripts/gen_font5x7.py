#!/usr/bin/env python3
"""Generate app/font5x7.h from the classic Adafruit GFX 5x7 font.

The source file scripts/glcdfont.c is the classic fixed-space bitmap font
shipped with Adafruit-GFX-Library (BSD licence, font derived from the
long-standing public-domain 5x7 terminal font).  Each glyph is 5 columns,
one byte per column, bit 0 = top row.

Run:  python3 scripts/gen_font5x7.py
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "glcdfont.c")
OUT = os.path.normpath(os.path.join(HERE, "..", "chiptune", "font5x7.h"))

FIRST = 32
LAST = 126


def load_bytes():
    with open(SRC, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()
    m = re.search(r"font\[\]\s*(?:PROGMEM)?\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("font array not found in %s" % SRC)
    raw = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1))]
    if len(raw) < 256 * 5:
        sys.exit("font array too short: %d bytes" % len(raw))
    return raw


def main():
    raw = load_bytes()
    lines = []
    lines.append("/* Generated by scripts/gen_font5x7.py from scripts/glcdfont.c.")
    lines.append(" * Classic 5x7 terminal font (Adafruit GFX, BSD licence).")
    lines.append(" * Each glyph: 5 columns, bit 0 is the top row. 6 px advance.")
    lines.append(" * Do not edit by hand. */")
    lines.append("")
    lines.append("#ifndef FONT5X7_H")
    lines.append("#define FONT5X7_H")
    lines.append("")
    lines.append("#define FONT5X7_W 5")
    lines.append("#define FONT5X7_HGT 7")
    lines.append("#define FONT5X7_ADV 6")
    lines.append("")
    lines.append("static const unsigned char font5x7[%d][5] = {" % (LAST - FIRST + 1))
    for c in range(FIRST, LAST + 1):
        vals = raw[c * 5:c * 5 + 5]
        hexs = ",".join("0x%02X" % v for v in vals)
        ch = chr(c)
        if ch == "\\":
            ch = "backslash"
        elif ch == "'":
            ch = "apostrophe"
        lines.append("\t{ %s }, /* 0x%02X %s */" % (hexs, c, ch))
    lines.append("};")
    lines.append("")
    lines.append("#endif /* FONT5X7_H */")
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
