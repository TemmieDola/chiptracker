#!/usr/bin/env bash
#
# Cross-build libopenmpt for FunKey OS (armv7-a, musl) and install the
# static library + public C headers into vendor/.
#
# Run once (or when VERSION changes):
#   bash scripts/build-libopenmpt.sh
#
# The result is cached: vendor/lib/libopenmpt.a.
# Build directory lives in $HOME so repeated WSL sessions do not re-download.
#
set -euo pipefail

VERSION="0.8.10+release"
TARBALL="libopenmpt-${VERSION}.autotools.tar.gz"
URL="https://lib.openmpt.org/files/libopenmpt/src/libopenmpt-0.8.10+release.autotools.tar.gz"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR="$ROOT/vendor"
OUT_LIB="$VENDOR/lib/libopenmpt.a"
OUT_INC="$VENDOR/include/libopenmpt"

if [ -f "$OUT_LIB" ] && [ -d "$OUT_INC" ]; then
	echo "== libopenmpt already built: $OUT_LIB"
	ls -l "$OUT_LIB"
	exit 0
fi

# ---------------------------------------------------------------- SDK ---
SDK="${FUNKEY_SDK:-$HOME/FunKey-sdk-2.3.0}"
if [ ! -d "$SDK" ] && [ -d /opt/FunKey-sdk ]; then
	SDK=/opt/FunKey-sdk
fi
if [ -d "$SDK" ]; then
	SDK="$(readlink -f "$SDK")"
fi

ENV_SETUP="$(find "$SDK" -maxdepth 2 -name 'environment-setup*' -type f | head -n 1 || true)"
if [ -z "${ENV_SETUP:-}" ]; then
	echo "ERROR: FunKey SDK environment-setup not found under $SDK" >&2
	exit 1
fi
# shellcheck disable=SC1090
. "$ENV_SETUP"

mkdir -p "$VENDOR" "$OUT_INC"

if [ ! -f "$VENDOR/$TARBALL" ]; then
	echo "== downloading $TARBALL"
	curl -L --fail -o "$VENDOR/$TARBALL" "$URL"
fi

BUILD="${LOMBT_BUILD_DIR:-$HOME/chiptune-libopenmpt-build}"
SRC="$BUILD/libopenmpt-${VERSION}.autotools"

if [ ! -d "$SRC" ]; then
	rm -rf "$BUILD"
	mkdir -p "$BUILD"
	echo "== extracting"
	tar -xzf "$VENDOR/$TARBALL" -C "$BUILD"
fi

# -Ofast from the SDK is not appropriate for a small ARM core and libopenmpt
# checks for -ffast-math explicitly.  Keep the SDK's default ARM/NEON target.
BASE_CFLAGS="-O2 -D_LARGEFILE_SOURCE -D_LARGEFILE64_SOURCE -D_FILE_OFFSET_BITS=64"
export CFLAGS="$BASE_CFLAGS"
export CXXFLAGS="$BASE_CFLAGS"

cd "$SRC"

if [ ! -f Makefile ]; then
	echo "== configure"
	./configure \
		--host=arm-funkey-linux-musleabihf \
		--build=x86_64-pc-linux-gnu \
		--disable-shared --enable-static \
		--disable-openmpt123 --disable-examples --disable-tests \
		--disable-doxygen-doc --disable-doxygen-html \
		--without-portaudio --without-portaudiocpp \
		--without-sndfile --without-flac \
		--without-ogg --without-vorbis --without-vorbisfile \
		--prefix="$BUILD/prefix"
fi

echo "== make -j$(nproc)"
set +e
make -j"$(nproc)"
MAKE_RC=$?
set -e

# libtool can fail on the final .la step because some SDK .la files contain
# build-host paths.  The static archive itself is produced before that and is
# all we need.
ARCHIVE="$(find "$SRC" -name 'libopenmpt.a' -type f | head -n 1 || true)"
if [ -z "$ARCHIVE" ]; then
	echo "ERROR: libopenmpt.a not produced (make rc=$MAKE_RC)" >&2
	exit 1
fi

mkdir -p "$VENDOR/lib"
cp "$ARCHIVE" "$OUT_LIB"
arm-funkey-linux-musleabihf-strip -g "$OUT_LIB" 2>/dev/null || true

# Public headers (libopenmpt_config.h is generated by configure).
for f in libopenmpt.h libopenmpt_config.h libopenmpt_version.h libopenmpt_ext.h; do
	[ -f "libopenmpt/$f" ] && cp "libopenmpt/$f" "$OUT_INC/$f"
done
cp "libopenmpt/libopenmpt.h" "$OUT_INC/libopenmpt.h"

cat >"$OUT_INC/README" <<EOF
libopenmpt $VERSION, cross-built for arm-funkey-linux-musleabihf.

Configured with: zlib + mpg123 (MO3 MP3 samples), no OGG/Vorbis,
no player/examples/tests.  Static archive only.

Source: $URL
Licence: BSD-3-Clause (see the libopenmpt source tree / vendor/LICENSE.libopenmpt).
EOF

echo
ls -l "$OUT_LIB"
file "$OUT_LIB"
echo "== done"
